import assert from "node:assert/strict";
import {mkdir} from "node:fs/promises";
import {chromium} from "playwright-core";
const base=process.env.FRONTEND_TEST_URL||"http://localhost:3100";
const dir=".impeccable/review/public-policies";await mkdir(dir,{recursive:true});
const browser=await chromium.launch({headless:true,...(process.env.BROWSER_PATH?{executablePath:process.env.BROWSER_PATH}:process.platform==="win32"?{executablePath:"C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe"}:{channel:"chrome"})});
try{
 const context=await browser.newContext({javaScriptEnabled:false,viewport:{width:1440,height:1000}});
 const page=await context.newPage();
 await page.goto(base+"/terms",{waitUntil:"domcontentloaded"});
 const terms=await page.locator("article").innerText();
 for(const term of ["120 days","14 business days","one-time","Pornography","Violence","Hate speech","CSAM","Deepfakes","Copyright","human review","not yet implemented","suspend","credits","gudexin748@gmail.com"]) assert.ok(terms.toLowerCase().includes(term.toLowerCase()),term);
 assert.ok(await page.locator("#models dl a").count()>0,"Specific models are absent from server-rendered terms");
 await page.screenshot({path:dir+"/terms-desktop.png",fullPage:true});
 await page.goto(base+"/refunds",{waitUntil:"domcontentloaded"});
 await page.getByRole("heading",{name:"Refund policy.",exact:true}).waitFor();
 const refund=await page.locator("article").innerText();
 assert.match(refund,/application window, not an unconditional/);
 assert.match(refund,/original payment method/);
 assert.match(refund,/Buyer Portal link/);
 assert.match(refund,/does not add a separate guaranteed/);
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:dir+"/refunds-mobile.png",fullPage:true});
 await page.goto(base+"/aup",{waitUntil:"domcontentloaded"});
 const report=page.locator('a[href^="mailto:"]').first();
 assert.match(await report.getAttribute("href"),/Content%20safety%20report/);
 assert.match(await page.locator("article").innerText(),/Independent platform screening/);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:dir+"/aup-mobile.png",fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(base+"/models",{waitUntil:"domcontentloaded"});
 assert.ok(await page.locator("article[data-model-key] h2").count()>0,"Catalogue requires JavaScript to show model names");
 assert.equal(await page.getByRole("button",{name:"Text",exact:true}).count(),0);
 await page.screenshot({path:dir+"/models-desktop.png",fullPage:true});
 await page.goto(base,{waitUntil:"domcontentloaded"});
 const footerContact=page.locator('footer a[href^="mailto:"]');
 assert.ok(await footerContact.count()>0,"Public footer has no direct support contact");
 assert.match(await footerContact.first().innerText(),/@/);
 const section=page.locator('section[aria-labelledby="home-models-title"]');
 assert.ok(await section.locator("dl a").count()>0,"Homepage model disclosure is missing");
 await section.screenshot({path:dir+"/home-models-desktop.png"});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await section.screenshot({path:dir+"/home-models-mobile.png"});
 await page.goto(base+"/privacy",{waitUntil:"domcontentloaded"});
 await page.getByRole("heading",{name:"Your privacy.",exact:true}).waitFor();
 const privacy=await page.locator("article").innerText();
 for(const fact of ["Alibaba Cloud Object Storage Service", "Where your data is stored", "File retention and deletion", "How your information is protected", "hashes", "encrypted", "HTTPS"]) assert.ok(privacy.includes(fact),fact);
 assert.doesNotMatch(privacy,/Not yet published|Checking published details/);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:dir+"/privacy-mobile.png",fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:dir+"/privacy-desktop.png",fullPage:true});
 await page.locator("footer").screenshot({path:dir+"/footer-desktop.png"});
 await browser.close();
 console.log("Public policies passed without JavaScript: specific live model names, refund eligibility/timing, six AUP categories, reporting/appeals, honest moderation limits, privacy route, desktop and mobile.");
}finally{await browser.close();}
